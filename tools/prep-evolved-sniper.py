#!/usr/bin/env python3
"""Prepare complete alpha components with shared anatomy scale and manual feet."""
import importlib.util, json
from pathlib import Path
import numpy as np
from PIL import Image
from scipy.ndimage import label, binary_dilation

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'tools/art-spike/sniper/evolved'
DEST = ROOT / 'v3/assets/authored/sniper/evolved'
spec = importlib.util.spec_from_file_location('sheet', ROOT/'tools/prep-authored-sheet.py')
sheet = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sheet)

def components(filename):
    im = Image.open(SOURCE/filename).convert('RGBA')
    rgba = np.array(im)
    labels, _ = label(rgba[:, :, 3] > 45)
    areas = np.bincount(labels.ravel())
    found = []
    for ident in np.flatnonzero(areas > 4000):
        if ident:
            ys, xs = np.where(labels == ident)
            found.append((int(ident), int(xs.min()), int(ys.min()), int(xs.max()+1), int(ys.max()+1)))
    return im, rgba, labels, found

def main():
    DEST.mkdir(parents=True, exist_ok=True)
    sources = {name: components(name) for name in ['sheet-source.webp', 'repair-source.webp']}
    # Original move/attack touch: reject that combined component entirely.
    assert len(sources['sheet-source.webp'][3]) == 6
    assert len(sources['repair-source.webp'][3]) == 2
    # Repair attack hood-to-boot is 743px; original standing reference is 510px.
    # Both repaired poses share that same calibration; crouches are never resized to standing height.
    repair_scale = .4 * 510 / 743
    jobs = [
        ('idle', 'sheet-source.webp', 1, (180, 520), .4),
        ('move', 'repair-source.webp', 1, (420, 755), repair_scale),
        ('attack', 'repair-source.webp', 2, (1450, 755), repair_scale),
        ('guard', 'sheet-source.webp', 3, (1290, 519), .4),
        ('signature', 'sheet-source.webp', 5, (210, 965), .4),
        ('hit', 'sheet-source.webp', 4, (800, 970), .4),
        ('defeat', 'sheet-source.webp', 6, (1210, 961), .4),
    ]
    registration = {'scale':1.26, 'referenceHeight':204, 'facing':1,
                    'actions':{'move':'move', 'retreat':'move', 'guard_close':'guard'}, 'poses':{}}
    manifest = {'fighter':'sniper', 'form':'evolved', 'status':'branch candidate; phone QA open',
                'repair_reason':'Original move barrel touches attack coat; combined component rejected.',
                'source_scale':.4, 'repair_source_scale':repair_scale, 'poses':[]}
    for name, filename, ident, foot, scale in jobs:
        im, rgba, labels, found = sources[filename]
        comp = next(c for c in found if c[0] == ident)
        assert comp[1]>0 and comp[2]>0 and comp[3]<im.width and comp[4]<im.height
        pixels = rgba.copy()
        pixels[:, :, 3][~binary_dilation(labels == ident, iterations=2)] = 0
        pose = Image.fromarray(pixels)
        bounds = pose.getbbox()
        crop = pose.crop(bounds)
        small = crop.resize((round(crop.width*scale), round(crop.height*scale)), Image.Resampling.LANCZOS)
        prepared = Image.new('RGBA', (small.width+12, small.height+12))
        prepared.alpha_composite(small, (6,6))
        prepared = sheet.add_outline(prepared)
        prepared.save(DEST/(name+'.webp'), 'WEBP', lossless=True, method=6)
        anchor = [((foot[0]-bounds[0])*scale+6)/prepared.width,
                  ((foot[1]-bounds[1])*scale+6)/prepared.height]
        assert all(0 <= a <= 1 for a in anchor)
        cues = {}
        weapon_points = {'attack':(1958,144), 'signature':(565,716)}
        body_points = {'idle':(180,260), 'move':(402,340), 'attack':(1410,345),
                       'guard':(1290,385), 'signature':(195,820), 'hit':(720,780), 'defeat':(1260,910)}
        for role, point in [('impact', body_points[name]), ('weapon', weapon_points.get(name))]:
            if point:
                cues[role] = [(point[0]-foot[0])*scale, (point[1]-foot[1])*scale]
        registration['poses'][name] = {'cues':cues, 'file':name, 'width':prepared.width,
                                      'height':prepared.height, 'anchor':anchor}
        manifest['poses'].append({'pose':name, 'source':filename, 'source_component_bounds':list(comp[1:]),
                                  'source_foot':foot, 'extraction_scale':scale, 'alpha_bounds':prepared.getbbox(),
                                  'identity':9, 'equipment':9, 'pose_clarity':8.5, 'critical_defects':[]})
    canonical = Image.open(SOURCE/'canonical-source.webp').convert('RGBA')
    canonical = sheet.add_outline(sheet.normalize(canonical, canvas=512, content=464, bottom=485))
    canonical.save(DEST/'presentation.webp', 'WEBP', lossless=True, method=6)
    (ROOT/'v3/evolved-sniper.js').write_text('// Generated by tools/prep-evolved-sniper.py. Shared anatomy scale; registered feet.\nwindow.SniperEvolvedArt='+json.dumps(registration,separators=(',',':'))+';\n')
    (SOURCE/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print('Prepared seven complete Sniper Evolved poses; touching originals excluded')

if __name__ == '__main__':
    main()
