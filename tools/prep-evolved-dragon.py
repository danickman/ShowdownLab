#!/usr/bin/env python3
"""Extract complete Dragon Evolved alpha poses and register feet/breath origins."""
import importlib.util, json, sys
sys.dont_write_bytecode=True
from pathlib import Path
import numpy as np
from PIL import Image
from scipy.ndimage import label, binary_dilation

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'tools/art-spike/dragon/evolved'
DEST=ROOT/'v3/assets/authored/dragon/evolved'
spec=importlib.util.spec_from_file_location('sheet',ROOT/'tools/prep-authored-sheet.py')
sheet=importlib.util.module_from_spec(spec);spec.loader.exec_module(sheet)

def components(filename):
    im=Image.open(SOURCE/filename).convert('RGBA');rgba=np.array(im)
    # Border pixels below 8 alpha are generated noise, not the drawn silhouette.
    rgba[:,:,3][rgba[:,:,3]<8]=0
    labels,_=label(rgba[:,:,3]>45);areas=np.bincount(labels.ravel());found=[]
    for ident in np.flatnonzero(areas>4000):
        if ident:
            ys,xs=np.where(labels==ident)
            found.append((int(ident),int(xs.min()),int(ys.min()),int(xs.max()+1),int(ys.max()+1)))
    return im,rgba,labels,found

def save_runtime(image,path):
    # Decode a complete temporary payload before replacing any runtime asset.
    pending=SOURCE/'runtime-export.tmp'
    image.save(pending,'WEBP',lossless=True,method=6)
    data=pending.read_bytes()
    assert data[:4]==b'RIFF' and data[8:12]==b'WEBP'
    with Image.open(pending) as checked:
        checked.load();assert checked.getbbox() and 'A' in checked.getbands()
    pending.replace(path)
    pending.unlink(missing_ok=True)

def main():
    DEST.mkdir(parents=True,exist_ok=True)
    sources={name:components(name) for name in ['sheet-source.webp','move-repair-source.webp']}
    assert len(sources['sheet-source.webp'][3])==7
    assert len(sources['move-repair-source.webp'][3])==1
    # A repaired single pose shares the original sheet's anatomy calibration.
    # Horn-to-front-foot reference is 270 source pixels on the original move;
    # 750 on the larger repair. Folded wings do not enlarge a shorter pose.
    repair_scale=.4*270/750
    jobs=[
        ('idle','sheet-source.webp',1,(317,390),.4),
        ('move','move-repair-source.webp',1,(994,853),repair_scale),
        ('attack','sheet-source.webp',3,(1260,385),.4),
        ('guard','sheet-source.webp',6,(244,762),.4),
        ('signature','sheet-source.webp',4,(810,769),.4),
        ('hit','sheet-source.webp',5,(1292,779),.4),
        ('defeat','sheet-source.webp',7,(756,1044),.4),
    ]
    registered={'scale':1.36,'referenceHeight':150.8,'facing':1,'poses':{}}
    manifest={'fighter':'dragon','form':'evolved','status':'review branch; phone QA open',
              'repair_reason':'Original move did not expose a distinct fourth foot; excluded.',
              'source_scale':.4,'repair_source_scale':repair_scale,'poses':[]}
    weapon={'attack':(1408,252),'signature':(944,514)}
    body={'idle':(341,281),'move':(1170,490),'attack':(1292,288),
          'guard':(281,636),'signature':(816,620),'hit':(1279,597),'defeat':(840,978)}
    for name,filename,ident,foot,scale in jobs:
        im,rgba,labels,found=sources[filename];comp=next(c for c in found if c[0]==ident)
        assert comp[1]>0 and comp[2]>0 and comp[3]<im.width and comp[4]<im.height
        pixels=rgba.copy();pixels[:,:,3][~binary_dilation(labels==ident,iterations=2)]=0
        pose=Image.fromarray(pixels);bounds=pose.getbbox();crop=pose.crop(bounds)
        small=crop.resize((round(crop.width*scale),round(crop.height*scale)),Image.Resampling.LANCZOS)
        prepared=Image.new('RGBA',(small.width+12,small.height+12));prepared.alpha_composite(small,(6,6))
        prepared=sheet.add_outline(prepared);save_runtime(prepared,DEST/(name+'.webp'))
        anchor=[((foot[0]-bounds[0])*scale+6)/prepared.width,((foot[1]-bounds[1])*scale+6)/prepared.height]
        assert all(0<=a<=1 for a in anchor)
        cues={}
        for role,point in [('impact',body[name]),('weapon',weapon.get(name))]:
            if point:cues[role]=[(point[0]-foot[0])*scale,(point[1]-foot[1])*scale]
        registered['poses'][name]={'file':name,'width':prepared.width,'height':prepared.height,'anchor':anchor,'cues':cues}
        manifest['poses'].append({'pose':name,'source':filename,'source_component_bounds':list(comp[1:]),
                                  'source_foot':foot,'extraction_scale':scale,'alpha_bounds':prepared.getbbox(),
                                  'identity':9,'equipment':9,'pose_clarity':8.5,'critical_defects':[]})
    canonical=Image.open(SOURCE/'canonical-source.webp').convert('RGBA')
    canonical=sheet.add_outline(sheet.normalize(canonical,canvas=512,content=464,bottom=485))
    save_runtime(canonical,DEST/'presentation.webp')
    (ROOT/'v3/evolved-dragon.js').write_text('// Generated by tools/prep-evolved-dragon.py. Shared anatomy scale, registered feet and mouth.\nwindow.DragonEvolvedArt='+json.dumps(registered,separators=(',',':'))+';\n')
    (SOURCE/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print('Prepared seven Dragon Evolved poses; original three-foot move excluded')

if __name__=='__main__':
    main()
