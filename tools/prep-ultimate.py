#!/usr/bin/env python3
"""Reproduce a reviewed Ultimate board from explicit registration.json. No automatic art scores."""
import argparse, importlib.util, json, sys
from pathlib import Path
import numpy as np
from PIL import Image
from scipy.ndimage import label, binary_dilation
sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('sheet', ROOT/'tools/prep-authored-sheet.py')
sheet = importlib.util.module_from_spec(spec); spec.loader.exec_module(sheet)

def extract(source, point, threshold=45):
    rgba = np.array(Image.open(source).convert('RGBA'))
    labels, _ = label(rgba[:,:,3] > threshold)
    ident = labels[point[1], point[0]]
    assert ident, ('registration point outside silhouette', source, point)
    ys, xs = np.where(labels == ident)
    bounds = [int(xs.min()), int(ys.min()), int(xs.max()+1), int(ys.max()+1)]
    assert min(bounds[:2]) > 0 and bounds[2] < rgba.shape[1] and bounds[3] < rgba.shape[0], ('source crop', source, bounds)
    rgba[:,:,3][~binary_dilation(labels == ident, iterations=2)] = 0
    im = Image.fromarray(rgba); bounds = im.getbbox()
    return im.crop(bounds), bounds

def main():
    parser = argparse.ArgumentParser(); parser.add_argument('fighter'); args = parser.parse_args()
    src = ROOT/'tools/art-spike'/args.fighter/'ultimate'
    jobs = json.loads((src/'registration.json').read_text())
    dest = ROOT/'v3/assets/authored'/args.fighter/'ultimate'; dest.mkdir(parents=True,exist_ok=True)
    metadata = {'scale':jobs['scale'], 'referenceHeight':jobs['referenceHeight'], 'facing':1,
                'actions':{'guard':'guard','guard_close':'guard'}, 'poses':{}}
    manifest = {'fighter':args.fighter,'form':'ultimate','status':'integrated; device QA open','poses':[]}
    for job in jobs['poses']:
        name=job['pose']; crop,bounds=extract(src/job['source'],job['componentPoint'],job.get('alphaThreshold',45))
        k=job['extractionScale']; small=crop.resize((round(crop.width*k),round(crop.height*k)),Image.Resampling.LANCZOS)
        out=Image.new('RGBA',(small.width+12,small.height+12)); out.alpha_composite(small,(6,6));out=sheet.add_outline(out)
        foot=job['foot'];anchor=[((foot[0]-bounds[0])*k+6)/out.width,((foot[1]-bounds[1])*k+6)/out.height]
        assert all(0<=a<=1 for a in anchor),(name,anchor)
        cues={role:[(p[0]-foot[0])*k,(p[1]-foot[1])*k] for role,p in job.get('cues',{}).items()}
        metadata['poses'][name]={'file':name,'width':out.width,'height':out.height,'anchor':anchor,'cues':cues}
        pending=dest/(name+'.tmp');out.save(pending,'WEBP',lossless=True,method=6)
        with Image.open(pending) as check:check.load();assert check.getbbox() and check.getchannel('A').getextrema()[0]==0
        pending.replace(dest/(name+'.webp'))
        manifest['poses'].append({**job,'sourceBounds':bounds,'alphaBounds':out.getbbox()})
    assert set(metadata['poses'])==set(['idle','move','attack','guard','signature','hit','defeat'])
    canonical=jobs['canonical'];crop,_=extract(src/canonical['source'],canonical['componentPoint'])
    canonical_pending=src/'canonical.tmp';crop.save(canonical_pending,'WEBP',lossless=True)
    with Image.open(canonical_pending) as check:check.load();assert check.getbbox()
    canonical_pending.replace(src/'canonical-source.webp')
    portrait=sheet.add_outline(sheet.normalize(crop,canvas=512,content=464,bottom=485))
    pending=dest/'presentation.tmp';portrait.save(pending,'WEBP',lossless=False,quality=96,method=4)
    with Image.open(pending) as check:check.load();assert check.size==(512,512) and check.getbbox()
    pending.replace(dest/'presentation.webp')
    global_name=args.fighter.title()+'UltimateArt'
    (ROOT/'v3'/('ultimate-'+args.fighter+'.js')).write_text('// Generated by tools/prep-ultimate.py; reviewed shared anatomy scale and individual feet/cues.\nwindow.'+global_name+'='+json.dumps(metadata,separators=(',',':'))+';\n')
    (src/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print('Prepared',args.fighter,'canonical + seven Ultimate poses')

if __name__=='__main__':main()
