'use strict';
// Playable Turtle Shell Rebound: direct real ultimate mechanics and truthful cue priority.
const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('assert/strict');
const base=path.resolve(__dirname,'../..'),read=p=>fs.readFileSync(path.join(base,p),'utf8');
const env={window:null,Math};env.window=env;vm.createContext(env);
vm.runInContext(read('v3/evolution-rules.js'),env);vm.runInContext(read('v3/ultimate-abilities.js'),env);
const u=env.ShowdownUltimates,m=(type,team,level,x,y,hp=100)=>({id:++m.id,type,team,level,x,y,hp,maxHp:100,dmg:40,action:'stab',stun:0,burrow:0});
m.id=0;
const turtle=m('turtle','blue',5,.45,.5),enemy=m('goblin','red',1,.49,.5),f1=m('goblin','red',1,.52,.5),f2=m('goblin','red',1,.54,.48),f3=m('goblin','red',1,.56,.5);
let hit=u.afterHit(enemy,turtle,20,[turtle,enemy,f1,f2,f3],100);
assert.equal(hit.length,4,'regular reflect and three bounded reprisal hits');
assert.equal(hit.filter(h=>h.source===turtle).length,3);
assert.equal(hit.find(h=>h.target===enemy&&h.source===turtle).damage,58);
assert.equal(hit.filter(h=>h.source===turtle&&h.target!==enemy).length,2);
assert.equal(f1.stun,8);assert.equal(f2.stun,8);assert.equal(f3.stun,0);
assert.equal(turtle.ultimateKind,'reprisal','reprisal visual supersedes same-tick reflect');
assert.equal(u.afterHit(enemy,turtle,20,[turtle,enemy,f1,f2,f3],110).filter(h=>h.source===turtle).length,0,'54 tick counter cooldown');
assert.equal(u.afterHit(enemy,turtle,20,[turtle,enemy,f1,f2,f3],154).filter(h=>h.source===turtle).length,3,'cooldown expires');
const l4=m('turtle','blue',4,.45,.5);assert.equal(u.afterHit(enemy,l4,20,[l4,enemy,f1,f2],200).filter(h=>h.source===l4).length,0,'L4 cannot reprisal');
const protectedAlly=m('knight','blue',3,.50,.5,35),guardian=m('turtle','blue',5,.43,.5),close=m('goblin','red',1,.52,.5);
hit=u.afterHit(close,protectedAlly,10,[protectedAlly,guardian,close],250);
assert.equal(hit.length,1);assert.equal(hit[0].source,guardian,'L5 guards real wounded ally');
assert.equal(guardian.ultimateKind,'reprisal');
const healthy=m('knight','blue',3,.5,.5,100),g2=m('turtle','blue',5,.43,.5);
assert.equal(u.afterHit(close,healthy,10,[healthy,g2,close],300).length,0,'healthy ally never invokes Turtle pulse');
const ranged=m('sniper','red',1,.92,.5);
assert.equal(u.afterHit(ranged,g2,10,[g2,ranged],360).filter(h=>h.source===g2).length,0,'far ranged attacks cannot cause counter-pulse');
const allyOutside=m('knight','blue',3,.25,.25,30),g3=m('turtle','blue',5,.45,.5);
assert.equal(u.afterHit(close,allyOutside,10,[allyOutside,g3,close],410).length,0,'outside .14 guardian coverage');
const same=m('knight','blue',3,.5,.5,20),g4=m('turtle','blue',5,.43,.5);
assert.equal(u.afterHit(same,g4,20,[same,g4],460).filter(h=>h.source===g4).length,0,'friendly attacks never proc Shell Rebound (pre-existing neutral reflection is separate)');
console.log('PASS: Turtle L5 playable actual primary shell rebound, 2 staggered splash, 54-tick cooldown, L4 untouched, guarded wounded ally, healthy/far/friendly rejection, and reprisal-over-reflect/shelter cue');
