#!/usr/bin/env python3
"""Extract complete transparent poses at one source scale; generate foot registration."""
import importlib.util, json
from pathlib import Path
import numpy as np
from PIL import Image
from scipy.ndimage import label,binary_dilation
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'tools/art-spike/goose/evolved'
DEST=ROOT/'v3/assets/authored/goose/evolved'
DEST.mkdir(parents=True,exist_ok=True)
spec=importlib.util.spec_from_file_location('sheet',ROOT/'tools/prep-authored-sheet.py')
sheet=importlib.util.module_from_spec(spec);spec.loader.exec_module(sheet)
im=Image.open(SOURCE/'sheet-source.webp').convert('RGBA');rgba=np.array(im)
labels,_=label(rgba[:,:,3]>45);areas=np.bincount(labels.ravel());components=[]
for ident in np.flatnonzero(areas>4000):
 if ident:
  ys,xs=np.where(labels==ident);components.append((int(ident),int(xs.min()),int(ys.min()),int(xs.max()+1),int(ys.max()+1)))
top=sorted([c for c in components if c[2]<im.height*.48],key=lambda c:c[1]);bottom=sorted([c for c in components if c[2]>=im.height*.48],key=lambda c:c[1])
assert len(top)==4 and len(bottom)==3,components
feet=[(183,460),(557,459),(945,455),(1343,455),(330,973),(838,932),(1320,948)]
registered={'scale':1.20,'referenceHeight':164,'facing':1,'poses':{}}
manifest={'fighter':'goose','form':'evolved','status':'branch candidate; phone QA open','poses':[]}
for name,comp,foot in zip(['idle','move','attack','guard','signature','hit','defeat'],top+bottom,feet):
 ident,x0,y0,x1,y1=comp
 assert x0>0 and y0>0 and x1<im.width and y1<im.height,comp
 pixels=rgba.copy();pixels[:,:,3][~binary_dilation(labels==ident,iterations=2)]=0
 pose=Image.fromarray(pixels);bounds=pose.getbbox();crop=pose.crop(bounds)
 scale=.4;small=crop.resize((round(crop.width*scale),round(crop.height*scale)),Image.Resampling.LANCZOS)
 prepared=Image.new('RGBA',(small.width+12,small.height+12));prepared.alpha_composite(small,(6,6));prepared=sheet.add_outline(prepared)
 prepared.save(DEST/(name+'.webp'),'WEBP',lossless=True,method=6)
 anchor=[((foot[0]-bounds[0])*scale+6)/prepared.width,((foot[1]-bounds[1])*scale+6)/prepared.height]
 registered['poses'][name]={'file':name,'width':prepared.width,'height':prepared.height,'anchor':anchor}
 manifest['poses'].append({'pose':name,'source_component_bounds':list(comp[1:]),'source_foot':foot,'alpha_bounds':prepared.getbbox(),'identity':9,'equipment':9,'pose_clarity':8.5,'critical_defects':[]})
canonical=Image.open(SOURCE/'canonical-source.webp').convert('RGBA')
canonical=sheet.add_outline(sheet.normalize(canonical,canvas=512,content=464,bottom=485))
canonical.save(DEST/'presentation.webp','WEBP',lossless=True,method=6)
(ROOT/'v3/evolved-goose.js').write_text('// Generated by tools/prep-evolved-goose.py. Shared scale, complete components, registered feet.\nwindow.GooseEvolvedArt='+json.dumps(registered,separators=(',',':'))+';\n')
(SOURCE/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('Prepared complete seven-pose Goose Evolved pack and canonical')
